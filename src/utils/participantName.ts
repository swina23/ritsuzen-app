/**
 * 参加者の氏名の正規化
 *
 * 通算成績の名寄せと、参加者マスターの重複チェックで同じ基準を使うためにここへ集約する。
 * 基準がずれると「マスターは別人として2件作れるのに、通算成績では同じ人として
 * 寄せようとする（または逆）」という噛み合わない状態になり、成績が割れる原因になる。
 */

/**
 * 保存する氏名を整える。全角括弧を半角に揃え、前後の空白を落とす。
 *
 * 括弧を揃えるのは、同じ人が「今村（梨）」「今村(梨)」の2件のマスターとして
 * 登録されるのを防ぐため。氏名の途中の空白は入力されたまま残す。
 * 「田中 太郎」のような姓名の区切りを勝手に詰めると表示が変わってしまうため。
 */
export const normalizeParticipantName = (name: string): string =>
  name.trim().replace(/（/g, '(').replace(/）/g, ')');

/**
 * 同じ人かどうかを比べるためのキー。表示には使わない。
 *
 * 保存時の正規化に加えて空白を全て落とす。「今村 (梨)」と「今村(梨)」は
 * 同じ人なので、マスターを2件作らせない。
 * 正規表現の \s は全角スペース(U+3000)も含むため、半角・全角どちらも落ちる。
 *
 * 揃えるのは空白と括弧だけに留める。「石川(桜)」と「石川」は別人であり、
 * 括弧の中身まで踏み込むと別人を統合してしまうため。
 */
export const participantNameKey = (name: string): string =>
  normalizeParticipantName(name).replace(/\s/g, '');
